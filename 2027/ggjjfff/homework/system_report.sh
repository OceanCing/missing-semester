#!/usr/bin/env bash
#
# Lesson 1 homework for the 27th season training course.
#
# What it does:
#   1. Print the current system time.
#   2. Print the last 10 shell commands.
#   3. Print the word / character count of the Markdown notes in ../notes.
#
# All output is redirected to output.txt next to this script.
#
# Usage:
#   bash homework/system_report.sh      # normal run
#   source homework/system_report.sh    # run inside the current shell, so that
#                                       # the live command history can be read
#
# Note about the command history:
#   A non-interactive script has no access to `history`, and bash only flushes
#   the current session to ~/.bash_history when the terminal is closed.
#   Run `history -a` before this script if you want the latest commands in it.

set -uo pipefail

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
NOTES_DIR="$(cd "${SCRIPT_DIR}/../notes" 2>/dev/null && pwd || echo "${SCRIPT_DIR}/../notes")"
OUTPUT_FILE="${SCRIPT_DIR}/output.txt"

# Allow overriding the notes file, otherwise use the first .md in ../notes.
if [ -z "${NOTES_FILE:-}" ]; then
    NOTES_FILE="$(find "${NOTES_DIR}" -maxdepth 1 -name '*.md' | sort | head -n 1)"
fi

# ---------------------------------------------------------------------------
# Section 1: current system time
# ---------------------------------------------------------------------------
print_time() {
    echo "=============================================="
    echo "[1] System time when the script was executed"
    echo "=============================================="
    date '+%Y-%m-%d %H:%M:%S %Z (%A)'
    echo
}

# ---------------------------------------------------------------------------
# Section 2: last 10 commands
# ---------------------------------------------------------------------------
print_history() {
    local recent=""

    # Preferred: the script was sourced into an interactive shell, so the
    # history builtin still works and contains the newest commands.
    recent="$(history 10 2>/dev/null | sed 's/^[[:space:]]*//')"

    # Fallback: read the history file written by bash.
    if [ -z "${recent}" ]; then
        local hist_file="${HISTFILE:-${HOME}/.bash_history}"
        if [ -r "${hist_file}" ]; then
            recent="$(tail -n 10 "${hist_file}")"
        fi
    fi

    echo "=============================================="
    echo "[2] The last 10 commands"
    echo "=============================================="
    if [ -n "${recent}" ]; then
        printf '%s\n' "${recent}"
    else
        echo "(no command history available)"
    fi
    echo
}

# ---------------------------------------------------------------------------
# Section 3: statistics of the notes
# ---------------------------------------------------------------------------
print_note_stats() {
    echo "=============================================="
    echo "[3] Statistics of my notes"
    echo "=============================================="

    if [ -z "${NOTES_FILE}" ] || [ ! -f "${NOTES_FILE}" ]; then
        echo "(notes file not found in ${NOTES_DIR})"
        echo
        return
    fi

    local words chars lines
    words="$(wc -w < "${NOTES_FILE}" | tr -d ' ')"
    chars="$(wc -m < "${NOTES_FILE}" | tr -d ' ')"
    lines="$(wc -l < "${NOTES_FILE}" | tr -d ' ')"

    echo "file       : $(basename "${NOTES_FILE}")"
    echo "words      : ${words}"
    echo "characters : ${chars}"
    echo "lines      : ${lines}"
    echo
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
{
    echo "Lesson 1 homework report"
    echo "generated by: homework/system_report.sh"
    echo
    print_time
    print_history
    print_note_stats
} > "${OUTPUT_FILE}"

echo "Report written to ${OUTPUT_FILE}"
